using System;
using UnityEngine;

public enum ScenarioWorkType
{
    FellTree,
    PlantJuvenile,
    RemoveRegeneration,
    PruneTree,
    SalvageDeadwood
}

public enum ScenarioWorkStatus
{
    Pending,
    Approved,
    Completed,
    Failed
}

public enum FellingMaterialOutcome
{
    SellAndExtract,
    RetainAsFallenDeadwood,
    KeepForUse
}

[Serializable]
public sealed class ScenarioOneWorkOrder
{
    public int workOrderId;
    public ScenarioWorkType type;
    public ScenarioWorkStatus status;
    public string targetTreeId = "";
    public string speciesId = "";
    public string stockItemId = "";
    public int requiredStockQuantity;
    public Vector3 worldPosition;
    public int cellIndex = -1;
    public FellingMaterialOutcome fellingOutcome;
    public int estimatedMinutes;
    public long estimatedCostCents;
    public long expectedRevenueCents;
    public float expectedVolumeM3;
    public float expectedRegenerationDensity;
    public float targetCrownBaseHeightM;
    public bool requiresCropTree;
    // v12 cell-based orders remain on the historical cohort pathway.
    public bool exactPosition;
    public string validationMessage = "";
    public int createdYear;
    public int resolvedYear = -1;
    public CCF.Forestry.WorkEconomy.WorkExecutionMethod executionMethod;
    public bool installShelter;
    public int harvestJobId = -1;
    // Version 21: the persisted Rack Planning & Field Marking V2 rack that owns this order.
    // 0 = not owned by a V2 rack (legacy orders and every save before v21). Declared last on
    // purpose so the world-hash compatibility path can remove exactly this default text.
    public int rackId;
    // Version 23 (MFM-06): durable provenance when this order was generated by an approved prescription.
    // prescriptionId 0 = an ordinary (manual) order: the other three fields are then required to be default.
    // The prescription record carries the rule version and source sample. Declared last and adjacent so the
    // hash compatibility path can remove exactly this default text.
    public int prescriptionId;
    // The coverage unit (ScenarioOneCoverage.Area.Id) the order was generated for.
    public string prescriptionCoverageUnitId = "";
    // The confirmed Crop Tree the order serves; empty when the reason does not name one.
    public string prescriptionCropTreeId = "";
    // Closed-vocabulary reason code: a ScenarioOnePrescription.ProposalReason value.
    public int prescriptionReason;

    public bool IsOpen => status == ScenarioWorkStatus.Pending || status == ScenarioWorkStatus.Approved;
    // A felling order that counts as planned progress: still open, valid, and
    // of the right type. Cancelled, completed and invalid orders do not count.
    public bool IsValidOpenFelling => type == ScenarioWorkType.FellTree && IsOpen && string.IsNullOrEmpty(validationMessage);

    public string ShortLabel
    {
        get
        {
            switch (type)
            {
                case ScenarioWorkType.FellTree: return "Fell " + targetTreeId;
                case ScenarioWorkType.SalvageDeadwood: return "Salvage " + targetTreeId;
                case ScenarioWorkType.PlantJuvenile: return "Plant " + speciesId + " at ("
                    + worldPosition.x.ToString("0.0") + ", " + worldPosition.z.ToString("0.0") + ")";
                case ScenarioWorkType.RemoveRegeneration: return string.IsNullOrEmpty(speciesId)
                    ? "Clear competing vegetation in map square " + ScenarioOneUiFacts.SquareLabel(cellIndex)
                    : "Remove " + speciesId + " regeneration in map square " + ScenarioOneUiFacts.SquareLabel(cellIndex);
                case ScenarioWorkType.PruneTree: return "Prune " + targetTreeId + " to "
                    + (targetCrownBaseHeightM > 0f ? targetCrownBaseHeightM : expectedRegenerationDensity).ToString("0.0") + " m";
                default: return type.ToString();
            }
        }
    }
}
