#!/usr/bin/env python3
"""Derive a disposable Model-2 completion MEASUREMENT from the Enlarged80 viability gate.

Why: ScenarioOneCompletionVerification asserts a Legacy40 start (336 Sitka) and cannot run on Enlarged80, and
Enlarged80ViabilityVerification ignores CCF_GROWTH_MODEL. The packet asks for the completion path under growth model 2
on both geometries, as a measurement and not a pass/fail anchor. This script copies the shipped Enlarged80 playthrough
(same stand, same thinning, same planting, same years) and changes ONLY:
  1. class names, so it does not collide with the shipped gate;
  2. it honours CCF_GROWTH_MODEL, like the Legacy40 completion gate does;
  3. the two end-of-run assertions become logged measurements, so a different outcome under model 2 is reported
     rather than thrown;
  4. it logs the final world hash.
Every replacement is asserted to match exactly once, so a changed source fails loudly instead of being half-patched.

Usage: make_e80_completion_measurement.py <output.cs>
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SOURCE = ROOT / "Tools/Verification/Enlarged80Calibration/Enlarged80ViabilityVerification.cs"

REPLACEMENTS = [
    ("Enlarged80ViabilityVerification", "Enlarged80CompletionMeasurement"),
    ("Enlarged80ViabilityRunner", "Enlarged80CompletionMeasurementRunner"),
    ('"E80 viability"', '"E80 completion measurement"'),
    ('"E80_VIABILITY_VERIFY_PASS":"E80_VIABILITY_VERIFY_FAIL "', '"E80_MEASUREMENT_DONE":"E80_MEASUREMENT_ERROR "'),
    ("marking=FindFirstObjectByType<ForestTreeMarkingManager>();",
     'marking=FindFirstObjectByType<ForestTreeMarkingManager>();'
     'string forcedGrowth=Environment.GetEnvironmentVariable("CCF_GROWTH_MODEL");'
     'if(!string.IsNullOrEmpty(forcedGrowth))ecology.GrowthModelVersion=int.Parse(forcedGrowth);'
     'Debug.Log("E80_MEASUREMENT_GROWTH_MODEL "+ecology.GrowthModelVersion+" forced="+(!string.IsNullOrEmpty(forcedGrowth)));'),
    ('Check(manager.Outcome==ScenarioOneOutcome.Completed && manager.OutcomeYear<=manager.Definition.MinimumCompletionYear,"not viable',
     'Debug.Log("E80_MEASUREMENT_COMPLETION completed="+(manager.Outcome==ScenarioOneOutcome.Completed)+" completedYear="+manager.OutcomeYear+" minimumYear="+manager.Definition.MinimumCompletionYear+" objectives="+string.Join(";",manager.Objectives.Select(ScenarioOneUiFacts.ObjectiveLine)));Check(true,"not viable'),
    ('Check(minimumCash>=0 && manager.AnnualReports.All(x=>x.ownerMinutes<=2400),"cash/owner constraint");',
     'Debug.Log("E80_MEASUREMENT_CASH_OWNER cashNeverNegative="+(minimumCash>=0)+" ownerWithinCapacity="+manager.AnnualReports.All(x=>x.ownerMinutes<=2400)+" minimumCash="+minimumCash);'
     'Debug.Log("E80_MEASUREMENT_WORLD_HASH "+ScenarioReferenceArchive.WorldHash(FindFirstObjectByType<ForestSaveController>().CaptureData()));'),
]


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    text = SOURCE.read_text()
    for old, new in REPLACEMENTS:
        count = text.count(old)
        if old.startswith("Enlarged80Viability"):
            if count < 1:
                raise SystemExit("expected at least one match for: " + old)
        elif count != 1:
            raise SystemExit("expected exactly one match (%d) for: %s" % (count, old[:80]))
        text = text.replace(old, new)
    header = ("// DERIVED MEASUREMENT - generated by make_e80_completion_measurement.py from Enlarged80ViabilityVerification.cs.\n"
              "// Not the shipped gate. See the generator for the four changes.\n")
    Path(sys.argv[1]).write_text(header + text)
    print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()
